-- 5. Verify ----------------------------------------------------------------------------
SELECT 'RAW_HUBS' AS TBL, COUNT(*) AS ROWS_LOADED FROM RAW_HUBS
UNION ALL SELECT 'RAW_VEHICLES',        COUNT(*) FROM RAW_VEHICLES
UNION ALL SELECT 'RAW_DRIVERS',         COUNT(*) FROM RAW_DRIVERS
UNION ALL SELECT 'RAW_CUSTOMERS',       COUNT(*) FROM RAW_CUSTOMERS
UNION ALL SELECT 'RAW_SHIPMENTS',       COUNT(*) FROM RAW_SHIPMENTS
UNION ALL SELECT 'RAW_SHIPMENT_EVENTS', COUNT(*) FROM RAW_SHIPMENT_EVENTS;

-- Which files were loaded, and were there any errors?
SELECT * FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
  TABLE_NAME => 'RAW_SHIPMENT_EVENTS',
  START_TIME => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
ORDER BY LAST_LOAD_TIME DESC
LIMIT 10;
